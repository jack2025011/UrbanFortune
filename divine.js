let DV_TOPIC=null,DV_LAST=-1;
function renderDivine(){
  $("#divine").innerHTML=`<div class="card"><h3>誠心默念，選擇你想問的事</h3>
    <div class="topic-grid">${DV_TOPICS.map(t=>`<button type="button" class="topic" data-topic="${t.id}"><span class="ti">${t.icon}</span><b>${t.name}</b><small>${t.desc}</small></button>`).join("")}</div>
    <p><small>選好事項後，靜下心來，系統會為你抽一支籤。</small></p></div>
    <div id="dv-result"></div>`;
  DV_TOPIC=null;
}
function drawStick(topicId){
  DV_TOPIC=topicId;
  const topic=DV_TOPICS.find(t=>t.id===topicId);
  const box=$("#dv-result");
  box.innerHTML=`<div class="card dv-wait"><p>搖籤中…</p></div>`;
  box.scrollIntoView({behavior:"smooth",block:"nearest"});
  setTimeout(()=>{
    // 有些籤主題很具體，只在相關的問題出現
    const pool=DV_STICKS.map((s,k)=>k).filter(k=>!DV_STICKS[k].only||DV_STICKS[k].only.includes(topicId));
    let i;do{i=pool[Math.floor(Math.random()*pool.length)]}while(i===DV_LAST&&pool.length>1);
    DV_LAST=i;const s=DV_STICKS[i];
    box.innerHTML=`<div class="card dv-card">
      <div class="dv-topic">所問：${topic.icon} ${topic.name}</div>
      <div class="dv-no">第 ${i+1} 籤</div>
      <div class="dv-level lv${s.l}">${DV_LEVELS[s.l]}</div>
      <div class="dv-title">「${s.t}」</div>
      <div class="dv-poem">${s.p.map(l=>`<div>${l}</div>`).join("")}</div>
      <button class="toggle in-card" data-target="dv-detail" data-label="籤詩解說">查看籤詩解說</button>
      <div id="dv-detail" class="hidden analysis">
        <h4>籤詩總解</h4><p>${s.e}</p>
        <h4>針對「${topic.name}」</h4><p>${DV_TOPIC_TEXT[topicId][s.l]}</p>
        <p class="note">籤詩為本站原創，僅供娛樂與自我反思，重要決定請以實際情況與專業意見為準。</p>
      </div>
      <div class="row2"><button class="ghost" type="button" data-again="1">再抽一次</button><button class="ghost" type="button" data-reset="1">換個問題</button></div>
    </div>`;
  },700);
}
document.addEventListener("click",e=>{
  const t=e.target.closest(".topic");if(t){drawStick(t.dataset.topic);return}
  if(e.target.closest("[data-again]")&&DV_TOPIC){drawStick(DV_TOPIC);return}
  if(e.target.closest("[data-reset]")){renderDivine();window.scrollTo({top:$("#divine").offsetTop-20,behavior:"smooth"})}
});
